def build(name: str) -> Path:
    e = BOARD[name]
    bg, out = Path(e["bg"]), Path(e["out"])
    refs = [Path(r) for r in e["refs"]]
    for p in [bg, *refs]:
        if not p.exists():
            raise SystemExit(f"missing input for {name}: {p}")
    key = os.environ.get("GOOGLE_API_KEY")
    if not key:
        raise SystemExit("GOOGLE_API_KEY missing (.env)")
    prompt = e["prompt"] + "\n\n" + e.get("preserve", PRESERVE)
    print(f"==> {name}: bg={bg.name} refs={[r.name for r in refs]} -> {out.name}")
    generate(bg, refs, prompt, out, key)
    print(f"    wrote {out}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Tango C board driver (AV ref-lock)")
    ap.add_argument("--only", help="comma-separated entry names")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    if a.list:
        for k, v in BOARD.items():
            print(f"{k:22s} -> {Path(v['out']).name}")
        return 0
    names = list(BOARD) if a.all else (a.only.split(",") if a.only else [])
    if not names:
        ap.error("pass --only <names>, --all, or --list")
    for n in names:
        build(n.strip())
    return 0


